import { jsPDF } from 'jspdf';
import 'jspdf-autotable';
import { shortProductCode, isCancelled } from './utils';
import { assignmentEarned, type GuideAssignmentRow } from './guidePerformance';

interface Guide {
  name: string;
  guide_number: string;
}

interface Booking {
  booking_ref: string;
  ext_ref?: string;
  customer_name: string;
  customer_phone?: string;
  travel_date: string;
  travel_time: string;
  product_code: string;
  option_name: string;
  channel: string;
  total_pax: number;
  pax_adult: number;
  pax_youth: number;
  pax_child: number;
  pax_infant: number;
  // Any channel can leave this blank until the owner fills it in — see BookingPanel/useBookings.
  gross_revenue: number | null;
  status: string;
}

export function generateGuideInvoice(
  guide: Guide,
  // Accepts the SAME unified rows the dashboards render (imported guide_assignments +
  // session-based pay via sessionGuidesToAssignmentRows — see guidePerformance.ts) so this PDF
  // can never fall behind what's shown on screen. A session-based row has no product_code/
  // pax_count (that data lives on the booking, not session_guides) — handled per-field below
  // rather than assumed present.
  assignments: GuideAssignmentRow[],
  companyName: string,
  dateRange: { from: string, to: string }
) {
  const doc: any = new jsPDF();
  const timestamp = new Date().getTime();

  // Header
  doc.setFontSize(24);
  doc.setTextColor(197, 165, 114); // Gold
  doc.text('AURELIA', 20, 25);
  
  doc.setFontSize(10);
  doc.setTextColor(100);
  doc.text(companyName.toUpperCase(), 20, 32);

  doc.setTextColor(0);
  doc.setFontSize(16);
  doc.text('GUIDE PAYMENT INVOICE', 120, 25);
  
  doc.setFontSize(9);
  doc.text(`Invoice #: GUI-${timestamp}`, 120, 32);
  doc.text(`Date: ${new Date().toLocaleDateString()}`, 120, 37);

  // Guide Info
  doc.setDrawColor(240);
  doc.line(20, 45, 190, 45);
  
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text('GUIDE INFORMATION', 20, 55);
  doc.setFont('helvetica', 'normal');
  doc.text(`Name: ${guide.name}`, 20, 62);
  doc.text(`ID: ${guide.guide_number}`, 20, 67);
  doc.text(`Period: ${dateRange.from} to ${dateRange.to}`, 20, 72);

  // Table — amount per row uses assignmentEarned(), the SAME earned-pay logic the dashboards use
  // (total_pay if set, else rate_override or calculated_pay, plus bonus), so every figure here
  // matches what the guide/owner already see on screen. A session-based row has no pax_count on
  // its own row (pax lives on the booking, not session_guides) — shown as "—" rather than a
  // fabricated or divide-by-zero rate.
  const tableData = assignments.map(a => {
    const amount = assignmentEarned(a);
    const pax = a.pax_count;
    const rate = pax && pax > 0 ? `€${(amount / pax).toFixed(2)}` : '—';
    return [
      a.travel_date || '—',
      a.travel_time || '—',
      a.product_code ? shortProductCode(a.product_code) : '—',
      a.tour_name || a.option_name || 'Tour',
      pax != null ? String(pax) : '—',
      rate,
      `€${amount.toFixed(2)}`,
    ];
  });

  const total = assignments.reduce((sum, a) => sum + assignmentEarned(a), 0);

  doc.autoTable({
    startY: 85,
    head: [['Date', 'Time', 'Product', 'Option', 'Pax', 'Rate', 'Amount']],
    body: tableData,
    headStyles: { fillColor: [197, 165, 114], textColor: [255, 255, 255] },
    alternateRowStyles: { fillColor: [250, 250, 250] },
    margin: { left: 20, right: 20 },
    theme: 'striped'
  });

  const finalY = (doc as any).lastAutoTable.finalY + 10;
  doc.setFont('helvetica', 'bold');
  doc.text(`Total Due: €${total.toFixed(2)}`, 190, finalY, { align: 'right' });

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(150);
  doc.text('Generated by AURELIA · aureliaio.netlify.app', 105, 285, { align: 'center' });
  doc.text('This is an automatically generated document', 105, 290, { align: 'center' });

  doc.save(`Guide_${guide.name.replace(/\s/g, '_')}_${dateRange.from}.pdf`);
}

/** Default company header for guide invoices when the owner's profile has no company name. */
export const DEFAULT_INVOICE_COMPANY = 'Scenic Zest Tours';

export interface GuideInvoiceGuide {
  name: string;
  guide_number: string | null;
  account_holder?: string | null;
  iban?: string | null;
  swift_code?: string | null;
  bank_name?: string | null;
}

export interface GuideInvoiceBonusLine {
  /** YYYY-MM */
  month: string;
  amount: number;
  note: string | null;
  paid: boolean;
}

const eur = (v: number) => `€${v.toFixed(2)}`;
const monthName = (ym: string) => {
  const [y, m] = ym.split('-').map(Number);
  return new Date(y, (m || 1) - 1, 1).toLocaleDateString('en-US', { month: 'long', year: 'numeric' });
};

/**
 * Period invoice for ONE guide — used by the admin (any guide) and by a guide for their own
 * months. Rows are the same unified tour rows the dashboards render (assignmentEarned for every
 * amount), plus month-end bonuses as their own lines. Pure rendering: reads nothing, writes
 * nothing, just saves a PDF.
 */
export function generateGuidePeriodInvoice(params: {
  guide: GuideInvoiceGuide;
  assignments: GuideAssignmentRow[];
  monthBonuses: GuideInvoiceBonusLine[];
  companyName?: string | null;
  periodLabel: string;
  dateRange: { from: string; to: string };
  paidThroughMonth: string | null;
}) {
  const { guide, monthBonuses, periodLabel, dateRange, paidThroughMonth } = params;
  const companyName = params.companyName || DEFAULT_INVOICE_COMPANY;
  const assignments = [...params.assignments].sort((a, b) =>
    `${a.travel_date || ''}${a.travel_time || ''}`.localeCompare(`${b.travel_date || ''}${b.travel_time || ''}`));
  const doc: any = new jsPDF();

  // Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.setTextColor(180, 83, 9);
  doc.text(companyName, 20, 24);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(120);
  doc.text('Guide payment invoice', 20, 30);

  doc.setTextColor(30);
  doc.setFontSize(10);
  doc.text(`Invoice date: ${new Date().toLocaleDateString()}`, 190, 22, { align: 'right' });
  doc.text(`Period: ${periodLabel}`, 190, 27, { align: 'right' });
  doc.setFontSize(8);
  doc.setTextColor(120);
  doc.text(`${dateRange.from} to ${dateRange.to}`, 190, 32, { align: 'right' });

  doc.setDrawColor(230);
  doc.line(20, 37, 190, 37);

  // Guide + bank details
  doc.setTextColor(30);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('GUIDE', 20, 46);
  doc.text('BANK DETAILS', 110, 46);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(guide.name, 20, 52);
  doc.text(`Guide no.: ${guide.guide_number || '—'}`, 20, 57);
  const bank = [
    `Account holder: ${guide.account_holder || '—'}`,
    `IBAN: ${guide.iban || '—'}`,
    `SWIFT/BIC: ${guide.swift_code || '—'}`,
    `Bank: ${guide.bank_name || '—'}`,
  ];
  bank.forEach((line, i) => doc.text(line, 110, 52 + i * 5));

  // Tours
  const body = assignments.map(a => {
    const total = assignmentEarned(a);
    const bonus = Number(a.bonus) || 0;
    return [
      a.travel_date || '—',
      a.tour_name || a.option_name || (a.product_code ? shortProductCode(a.product_code) : 'Tour'),
      a.tour_type || '—',
      a.pax_count != null ? String(a.pax_count) : '—',
      eur(total - bonus),
      bonus ? eur(bonus) : '—',
      eur(total),
    ];
  });
  const bonusRows = monthBonuses.map(b => [
    b.month, `Month-end bonus — ${monthName(b.month)}${b.note ? ` (${b.note})` : ''}`, 'Bonus', '—', '—', eur(b.amount), eur(b.amount),
  ]);

  doc.autoTable({
    startY: 76,
    head: [['Date', 'Tour', 'Type', 'Pax', 'Pay', 'Bonus', 'Total']],
    body: [...body, ...bonusRows],
    headStyles: { fillColor: [180, 83, 9], textColor: [255, 255, 255] },
    alternateRowStyles: { fillColor: [250, 248, 244] },
    styles: { fontSize: 8, cellPadding: 2 },
    columnStyles: { 3: { halign: 'right' }, 4: { halign: 'right' }, 5: { halign: 'right' }, 6: { halign: 'right' } },
    margin: { left: 20, right: 20 },
    theme: 'striped',
  });

  // Totals — paid/pending use the same rules as the dashboards: a tour by its own is_paid, a
  // month-end bonus by its month's payment status.
  const tourTotal = assignments.reduce((s, a) => s + assignmentEarned(a), 0);
  const tourPaid = assignments.filter(a => a.is_paid).reduce((s, a) => s + assignmentEarned(a), 0);
  const bonusTotal = monthBonuses.reduce((s, b) => s + b.amount, 0);
  const bonusPaid = monthBonuses.filter(b => b.paid).reduce((s, b) => s + b.amount, 0);
  const total = tourTotal + bonusTotal;
  const paid = tourPaid + bonusPaid;

  let y = (doc as any).lastAutoTable.finalY + 10;
  if (y > 250) { doc.addPage(); y = 25; }
  const line = (label: string, value: string, bold = false) => {
    doc.setFont('helvetica', bold ? 'bold' : 'normal');
    doc.text(label, 130, y);
    doc.text(value, 190, y, { align: 'right' });
    y += 6;
  };
  doc.setFontSize(9);
  doc.setTextColor(30);
  line(`Tours subtotal (${assignments.length})`, eur(tourTotal));
  if (monthBonuses.length) line('Month-end bonus', eur(bonusTotal));
  doc.setDrawColor(220);
  doc.line(130, y - 3, 190, y - 3);
  doc.setFontSize(11);
  line('Total', eur(total), true);
  doc.setFontSize(9);
  line('Amount paid', eur(paid));
  line('Amount pending', eur(total - paid), true);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(120);
  doc.text(`Paid through: ${paidThroughMonth ? monthName(paidThroughMonth) : '—'}`, 130, y + 2);

  doc.setFontSize(8);
  doc.text('Generated by AURELIA', 105, 288, { align: 'center' });

  doc.save(`Invoice_${guide.name.replace(/\s+/g, '_')}_${dateRange.from}_${dateRange.to}.pdf`);
}

export function generateBookingInvoice(
  booking: Booking,
  companyName: string
) {
  const doc: any = new jsPDF();

  // Header
  doc.setFontSize(20);
  doc.setTextColor(197, 165, 114);
  doc.text(companyName.toUpperCase(), 20, 25);
  
  doc.setTextColor(0);
  doc.setFontSize(16);
  doc.text('BOOKING INVOICE', 120, 25);

  // Details
  doc.setFontSize(10);
  doc.text(`Ref: ${booking.booking_ref}`, 20, 45);
  doc.text(`Ext Ref: ${booking.ext_ref || '—'}`, 20, 50);
  doc.text(`Customer: ${booking.customer_name}`, 20, 55);
  doc.text(`Phone: ${booking.customer_phone || '—'}`, 20, 60);
  
  doc.text(`Travel: ${booking.travel_date} at ${booking.travel_time}`, 120, 45);
  doc.text(`Product: ${shortProductCode(booking.product_code)}`, 120, 50);
  doc.text(`Option: ${booking.option_name}`, 120, 55);
  doc.text(`Channel: ${booking.channel}`, 120, 60);

  // Passengers
  doc.setDrawColor(245);
  doc.setFillColor(250, 250, 250);
  doc.rect(20, 70, 170, 15, 'F');
  doc.setFontSize(9);
  doc.text(`Adults: ${booking.pax_adult} | Youth: ${booking.pax_youth} | Children: ${booking.pax_child} | Infant: ${booking.pax_infant} | TOTAL: ${booking.total_pax}`, 105, 79, { align: 'center' });

  // Financials Mockup (as requested) — gross_revenue can be null (needs input, not yet filled
  // in by the owner); treated as 0 here rather than crashing the PDF on a still-blank booking.
  const grossRevenue = booking.gross_revenue ?? 0;
  const otaComm = grossRevenue * 0.2; // 20% default mockup
  const netRev = grossRevenue - otaComm;

  doc.autoTable({
    startY: 95,
    body: [
      ['Gross Revenue', booking.gross_revenue === null ? 'Needs input' : `€${grossRevenue.toFixed(2)}`],
      ['OTA Commission (Est. 20%)', `-€${otaComm.toFixed(2)}`],
      ['Net Revenue', `€${netRev.toFixed(2)}`],
      ['', ''],
      ['Ticket Costs (Est.)', '-€0.00'],
      ['Guide Costs (Est.)', '-€0.00'],
      ['Extra Costs', '-€0.00'],
      ['', ''],
      ['NET PROFIT (Est.)', `€${netRev.toFixed(2)}`]
    ],
    theme: 'plain',
    styles: { fontSize: 10, cellPadding: 4 },
    columnStyles: { 1: { halign: 'right', fontStyle: 'bold' } },
    margin: { left: 40, right: 40 }
  });

  const finalY = (doc as any).lastAutoTable.finalY + 15;
  doc.setFontSize(12);
  const statusColor = booking.status === 'DONE' ? [34, 197, 94] : isCancelled(booking.status) ? [239, 68, 68] : [197, 165, 114];
  doc.setTextColor(statusColor[0], statusColor[1], statusColor[2]);
  doc.text(`STATUS: ${booking.status}`, 105, finalY, { align: 'center' });

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(150);
  doc.text('AURELIA PLATFORM · POWERING OPERATIONAL INTELLIGENCE', 105, 285, { align: 'center' });

  doc.save(`Invoice_${booking.booking_ref}.pdf`);
}
